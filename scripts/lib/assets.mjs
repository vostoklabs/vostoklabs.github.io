/*
  The asset registry: every font, typeface, icon set, symbol set, pattern set and model an app
  bundles, with where it came from and the licence it ships under.

    assets.json           rows for published files (committed, like generators.json)
    assets.private.json   rows for gitignored files (gitignored), so no committed file names one

  A row is { id, kind, files: { path: sha256 }, licence, copyright, reservedNames, shipsAs,
  source: { url, commit }, licenceUrl, notice, writtenBy }. `licence` is an SPDX expression;
  `shipsAs` is "original" (the upstream file, byte for byte), "cut" (a subset or an instance of
  it) or "converted" (the same outlines or data in another format); `notice` lists the licence
  texts that travel with it. A copy of a file elsewhere in the repo is claimed by its sha256, so
  the row lists only the files its writer manages. Which apps carry a row is derived from their
  source (scripts/lib/bundle.mjs), never stored.

  Written by packages/fonts/scripts/fetch-fonts.mjs (the faces it fetches, with their family's
  licence read upstream) and by scripts/assets.mjs (everything else). Checked by
  scripts/check-assets.mjs.
*/

import { readFileSync, writeFileSync, existsSync, unlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { brotliDecompressSync, inflateSync } from 'node:zlib';
import { abs, ignored } from './source.mjs';

/** The licences anything shipped may carry (CLAUDE.md, invariant #6). An OFL face may not be
 *  shipped modified under a name its licence reserves. */
export const ALLOWED = ['OFL-1.1', 'Apache-2.0', 'MIT', 'ISC', 'CC0-1.0'];

export const REGISTRY = 'assets.json';
export const PRIVATE_REGISTRY = 'assets.private.json';

const ORDER = ['id', 'kind', 'files', 'licence', 'copyright', 'reservedNames', 'shipsAs', 'source', 'licenceUrl', 'notice', 'writtenBy'];
const COMMENT = 'Generated by scripts/assets.mjs and packages/fonts/scripts/fetch-fonts.mjs; do not edit by hand. pnpm check:assets holds every font, typeface, symbol, pattern and model file to a row here.';

/** What kind of asset a file is by its name, or null for a file the check does not hold to a
 *  row: fonts, three.js typefaces, models, and the data of a symbol or pattern set. */
export function assetKind(path) {
  if (/\.(?:ttf|otf|woff2?)$/i.test(path)) return 'font';
  if (/\.typeface\.json$/i.test(path)) return 'typeface';
  if (/\.onnx$/i.test(path)) return 'model';
  if (/(?:^|\/)(?:symbols|patterns)\/(?:.*\/)?[^/]+\.json$/i.test(path)) return 'data';
  return null;
}

export const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

/** Text files are hashed with LF line ends, as git stores them: a Windows checkout turns each
 *  LF into CRLF, which is not a change to the file. Fonts, models and other binaries are hashed
 *  as they are. */
const TEXT = /\.(?:json|[cm]?[jt]sx?|svg|txt|md|css|html)$/i;

/** The sha256 a row records for a repo file. */
export function fileHash(path, buf = readFileSync(abs(path))) {
  if (!TEXT.test(path)) return sha256(buf);
  const lf = Buffer.alloc(buf.length);
  let n = 0;
  for (let i = 0; i < buf.length; i++) if (!(buf[i] === 0x0d && buf[i + 1] === 0x0a)) lf[n++] = buf[i];
  return sha256(lf.subarray(0, n));
}

/** Whether an SPDX expression is allowed: every term of an AND, at least one of an OR. */
export function licenceAllowed(expr) {
  const text = String(expr ?? '').trim();
  if (!text || /[()]/.test(text)) return false;
  return text.split(/\s+OR\s+/).some((alt) => alt.split(/\s+AND\s+/).every((id) => ALLOWED.includes(id.trim())));
}

/** Code-point order, the same on every machine (localeCompare follows the system's locale). */
const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const readJson = (rel) => (existsSync(abs(rel)) ? JSON.parse(readFileSync(abs(rel), 'utf8')) : null);

/** Every row, the private file's merged in: a row in both has the files of both. */
export function readRegistry() {
  const byId = new Map();
  for (const file of [REGISTRY, PRIVATE_REGISTRY]) {
    for (const row of readJson(file)?.assets ?? []) {
      const had = byId.get(row.id);
      if (had) had.files = { ...had.files, ...row.files };
      else byId.set(row.id, { ...row, files: { ...row.files } });
    }
  }
  return [...byId.values()];
}

/** Every file the published registry names. */
export const publicPaths = () => (readJson(REGISTRY)?.assets ?? []).flatMap((row) => Object.keys(row.files));

/** Writes the rows: each row's published files to assets.json and its gitignored ones to
 *  assets.private.json, under the same id. The private file is written only where there is
 *  something private to say. */
export function writeRegistry(rows) {
  const paths = rows.flatMap((r) => Object.keys(r.files));
  const hidden = ignored(paths);
  // One key order for every row, whoever wrote it.
  const ordered = (row) => Object.fromEntries(Object.entries(row).sort(([a], [b]) => ((ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99))));
  const half = (keep) => rows
    .map((row) => ordered({ ...row, files: Object.fromEntries(Object.entries(row.files).filter(([p]) => keep(hidden.has(p))).sort(([a], [b]) => byCode(a, b))) }))
    .filter((row) => Object.keys(row.files).length)
    .sort((a, b) => byCode(a.id, b.id));
  const text = (assets) => `${JSON.stringify({ $comment: COMMENT, assets }, null, 2)}\n`;
  writeFileSync(abs(REGISTRY), text(half((h) => !h)));
  const privateRows = half((h) => h);
  if (privateRows.length) writeFileSync(abs(PRIVATE_REGISTRY), text(privateRows));
  else if (existsSync(abs(PRIVATE_REGISTRY))) unlinkSync(abs(PRIVATE_REGISTRY));
}

/** Replaces every row `writtenBy` wrote with `rows`, keeping everyone else's. */
export function recordAssets(writtenBy, rows) {
  const kept = readRegistry().filter((r) => r.writtenBy !== writtenBy);
  writeRegistry([...kept, ...rows.map((r) => ({ ...r, writtenBy }))]);
}

const hashes = new Map();
/** `fileHash` of a repo file, read once. */
export function hashOf(path) {
  if (!hashes.has(path)) hashes.set(path, fileHash(path));
  return hashes.get(path);
}

/** The ids of the rows that claim any of `files` (repo paths, such as what an app's build
 *  reaches): by the path a row names, or by the bytes of a copy. */
export function rowsClaiming(files, rows = readRegistry()) {
  const byPath = new Map();
  const byHash = new Map();
  for (const row of rows) {
    for (const [path, hash] of Object.entries(row.files)) {
      byPath.set(path, [...(byPath.get(path) ?? []), row.id]);
      byHash.set(hash, [...(byHash.get(hash) ?? []), row.id]);
    }
  }
  const ids = new Set();
  for (const path of files) {
    const named = byPath.get(path);
    if (named) for (const id of named) ids.add(id);
    else if (assetKind(path) && existsSync(abs(path))) for (const id of byHash.get(hashOf(path)) ?? []) ids.add(id);
  }
  return ids;
}

