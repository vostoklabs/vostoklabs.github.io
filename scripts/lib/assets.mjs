/** The strings of a font's name table by name ID: Windows English first, then any Unicode
 *  record, then Macintosh. */
function nameTable(t) {
  const out = {};
  const score = {};
  const count = t.readUInt16BE(2);
  const storage = t.readUInt16BE(4);
  for (let i = 0; i < count; i++) {
    const r = 6 + i * 12;
    const platform = t.readUInt16BE(r);
    const lang = t.readUInt16BE(r + 4);
    const id = t.readUInt16BE(r + 6);
    const raw = t.subarray(storage + t.readUInt16BE(r + 10), storage + t.readUInt16BE(r + 10) + t.readUInt16BE(r + 8));
    const text = platform === 1 ? raw.toString('latin1') : Buffer.from(raw.subarray(0, raw.length & ~1)).swap16().toString('utf16le');
    const s = platform === 3 && lang === 0x409 ? 2 : platform === 3 || platform === 0 ? 1 : 0;
    if (!(id in out) || s > score[id]) { out[id] = text; score[id] = s; }
  }
  return out;
}

/** The name table of an sfnt (TrueType or OpenType) file. */
function sfntNames(buf) {
  for (let i = 0, n = buf.readUInt16BE(4); i < n; i++) {
    const r = 12 + i * 16;
    if (buf.toString('latin1', r, r + 4) === 'name') return nameTable(buf.subarray(buf.readUInt32BE(r + 8), buf.readUInt32BE(r + 8) + buf.readUInt32BE(r + 12)));
  }
  return {};
}

/** WOFF 1: each table zlib-compressed on its own. */
function woffNames(buf) {
  for (let i = 0, n = buf.readUInt16BE(12); i < n; i++) {
    const r = 44 + i * 20;
    if (buf.toString('latin1', r, r + 4) !== 'name') continue;
    const data = buf.subarray(buf.readUInt32BE(r + 4), buf.readUInt32BE(r + 4) + buf.readUInt32BE(r + 8));
    return nameTable(buf.readUInt32BE(r + 8) < buf.readUInt32BE(r + 12) ? inflateSync(data) : data);
  }
  return {};
}

/** The tags a WOFF2 table directory names by index (the WOFF2 specification, 5.1). */
const WOFF2_TAGS = 'cmap head hhea hmtx maxp name OS/2 post cvt  fpgm glyf loca prep CFF  VORG EBDT EBLC gasp hdmx kern LTSH PCLT VDMX vhea vmtx BASE GDEF GPOS GSUB EBSC JSTF MATH CBDT CBLC COLR CPAL SVG  sbix acnt avar bdat bloc bsln cvar fdsc feat fmtx fvar gvar hsty just lcar mort morx opbd prop trak Zapf Silf Glat Gloc Feat Sill'.match(/.{4}\s?/g).map((t) => t.slice(0, 4));

/** WOFF2: one Brotli stream holding every table in directory order. The name table is never
 *  transformed, so it can be read straight out of the stream. */
function woff2Names(buf) {
  let p = 48;
  const varint = () => {
    let v = 0;
    for (let i = 0; i < 5; i++) {
      const b = buf[p++];
      v = v * 128 + (b & 0x7f);
      if (!(b & 0x80)) return v;
    }
    throw new Error('bad WOFF2 table directory');
  };
  const tables = [];
  for (let i = 0, n = buf.readUInt16BE(12); i < n; i++) {
    const flags = buf[p++];
    const tag = (flags & 0x3f) === 63 ? buf.toString('latin1', p, (p += 4)) : WOFF2_TAGS[flags & 0x3f];
    const length = varint();
    const version = flags >> 6;
    const transformed = tag === 'glyf' || tag === 'loca' ? version !== 3 : version !== 0;
    tables.push({ tag, length: transformed ? varint() : length });
  }
  const stream = brotliDecompressSync(buf.subarray(p, p + buf.readUInt32BE(20)));
  let at = 0;
  for (const t of tables) {
    if (t.tag === 'name') return nameTable(stream.subarray(at, at + t.length));
    at += t.length;
  }
  return {};
}

/** A font file's name table, whatever its container. */
export function fontNames(buf) {
  const sig = buf.toString('latin1', 0, 4);
  if (sig === 'wOF2') return woff2Names(buf);
  if (sig === 'wOFF') return woffNames(buf);
  return sfntNames(buf);
}

/** What a file says about its own licence and names: a font's name table, a typeface's
 *  `original_font_information`, a data set's own `licence` field. Empty for a file that says
 *  nothing (a model). */
export function embedded(path, buf) {
  const kind = assetKind(path);
  if (kind === 'font') {
    const n = fontNames(buf);
    return { names: [n[1], n[4], n[6], n[16]].filter(Boolean), copyright: n[0] ?? '', licence: [n[0], n[13], n[14]].filter(Boolean).join('\n') };
  }
  if (kind === 'typeface') {
    const i = JSON.parse(buf.toString('utf8')).original_font_information ?? {};
    return {
      names: [i.font_family_name, i.full_font_name, i.postscript_name].filter(Boolean),
      copyright: i.copyright ?? '',
      licence: [i.copyright, i.license_description, i.license_url].filter(Boolean).join('\n'),
    };
  }
  if (kind === 'data') {
    const head = buf.subarray(0, 2048).toString('utf8');
    const m = head.match(/"licen[cs]e"\s*:\s*"([^"]*)"/i);
    return { names: [], copyright: '', licence: m ? m[1] : '' };
  }
  return { names: [], copyright: '', licence: '' };
}

/** Licence terms none of the allowed licences has: what a row claiming one of them must not
 *  find in the file it claims. */
const FORBIDDEN = [
  [/\beula|end[- ]user\s+licen[cs]e/i, 'an end-user licence agreement'],
  [/\bpersonal\b(?:\s+\w+){0,4}\s+use\b/i, 'personal-use terms'],
  [/non-?\s?commercial/i, 'non-commercial terms'],
  [/no\s*-?\s*deriv/i, 'no-derivatives terms'],
  [/\bL?GPL\b|GNU\s+(?:Lesser\s+|Library\s+)?General\s+Public\s+Licen[cs]e/i, 'the GPL'],
  [/creative\s+commons\s+attribution|\bCC[- ]BY\b/i, 'CC BY'],
];
/** How a file names an allowed licence. */
const NAMED = [
  ['OFL-1.1', /SIL Open Font Licen[cs]e|\bOFL\b|openfontlicense\.org|scripts\.sil\.org\/OFL/i],
  ['Apache-2.0', /\bApache\s+(?:Licen[cs]e|2\.0)|apache\.org\/licenses/i],
  ['MIT', /\bMIT\b/],
  ['ISC', /\bISC\b/],
  ['CC0-1.0', /\bCC0\b|creativecommons\.org\/publicdomain\/zero/i],
];

/** The allowed licences a file's own licence text names. */
export const licencesNamedIn = (text) => NAMED.filter(([, re]) => re.test(String(text ?? ''))).map(([id]) => id);

/** Why a file's own licence text contradicts `licence`, or null when it does not: it states
 *  terms no allowed licence has, or it names licences of which `licence` is none. */
export function contradiction(text, licence) {
  if (!text) return null;
  for (const [re, what] of FORBIDDEN) if (re.test(text)) return `the file's own licence text states ${what}`;
  const named = licencesNamedIn(text);
  const claimed = String(licence).split(/\s+(?:AND|OR)\s+/);
  if (named.length && !named.some((id) => claimed.includes(id))) return `the file's own licence text names ${named.join(' and ')}, not ${licence}`;
  return null;
}

