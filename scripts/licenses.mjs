/*
  Writes apps/<id>/LICENSE.md for every generator app.

    node scripts/licenses.mjs          # write them all
    node scripts/licenses.mjs --check  # fail if any is missing or out of date
    pnpm gen:licenses
    pnpm check:licenses

  Why generated rather than nine hand-written files: the licence text quotes a price and
  a sign-up URL, and invariant #4 says those live in `config/brand.ts` and nowhere else.
  A markdown file cannot import brand, so this reads brand and writes the markdown. The
  two files that existed before this script hardcoded "$15/month" and the MakerWorld
  link, and had already drifted apart from each other — the keycap one never got the
  commercial section the clicker one grew.

  The commercial half is a restatement of the MakerWorld membership terms, so that a
  person reading a repo file and a person reading the membership page are agreeing to the
  same thing. The membership page stays authoritative and says so in the text: these are
  nine copies, and nine copies drift.

  `licenseMarkdown()` is exported so `new-generator.mjs` can write a correct LICENSE.md
  for a new app at scaffold time, instead of copying the template's and leaving another
  app's name in a legal document.
*/

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** Apps that are not generators: the hub is the site itself, kit-demo is the component
 *  gallery. Neither produces a design anyone could sell. */
const NOT_GENERATORS = new Set(['hub', 'kit-demo']);

/** Fixed, not `new Date()`. Regenerating in a later year should not silently rewrite the
 *  copyright line on every app — that is a decision, not a side effect of running a script. */
const YEAR = 2026;

// ────────────────────────────────── brand ──────────────────────────────────

/** `config/brand.ts` is a plain object literal behind `as const`. Rather than pull a TS
 *  toolchain into a script that needs two strings out of it, lift the literal and
 *  evaluate it — and assert on the way out, so a change to brand's SHAPE fails loudly
 *  here instead of quietly writing a licence with `undefined/month` in it. */
export function readBrand() {
  const src = readFileSync(join(ROOT, 'config', 'brand.ts'), 'utf8');
  const start = src.indexOf('export const BRAND = ');
  const end = src.indexOf('} as const;', start);
  if (start < 0 || end < 0) throw new Error('config/brand.ts: cannot find `export const BRAND = { … } as const;`');

  const literal = src.slice(start + 'export const BRAND = '.length, end + 1);
  const brand = new Function(`return (${literal});`)();

  const price = brand?.pricing?.subscription;
  const url = brand?.urls?.mwCommercial;
  if (!price?.month || !price?.quarter || !price?.year || !price?.covers) {
    throw new Error('config/brand.ts: pricing.subscription is missing month/quarter/year/covers');
  }
  if (!url || String(url).startsWith('TODO')) {
    throw new Error(`config/brand.ts: urls.mwCommercial is not set (got ${url})`);
  }
  return brand;
}

// ────────────────────────────────── text ──────────────────────────────────

