// ────────────────────────────────── apps ──────────────────────────────────

/** The app's own page title, minus the site suffix — so the licence names the thing the
 *  user actually used. Falls back to the directory name. */
export function appTitle(appDir) {
  const indexPath = join(appDir, 'index.html');
  if (!existsSync(indexPath)) return basename(appDir);
  const m = readFileSync(indexPath, 'utf8').match(/<title>([^<]*)<\/title>/i);
  if (!m) return basename(appDir);
  return m[1].split(/\s+[·|-]\s+/)[0].trim() || basename(appDir);
}

export function generatorApps() {
  const appsDir = join(ROOT, 'apps');
  return readdirSync(appsDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !NOT_GENERATORS.has(e.name))
    .filter((e) => existsSync(join(appsDir, e.name, 'index.html')))
    .map((e) => e.name);
}

function main() {
  const check = process.argv.includes('--check');
  const rows = [];
  const stale = [];

  for (const id of generatorApps()) {
    const appDir = join(ROOT, 'apps', id);
    const path = join(appDir, 'LICENSE.md');
    const title = appTitle(appDir);
    const wanted = licenseMarkdown({ title });
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;

    if (check) {
      const state = current === null ? 'MISSING' : current === wanted ? 'ok' : 'OUT OF DATE';
      if (state !== 'ok') stale.push(`apps/${id}/LICENSE.md — ${state}`);
      rows.push(`  ${state.padEnd(11)} apps/${id}/LICENSE.md`);
      continue;
    }

    writeFileSync(path, wanted, 'utf8');
    rows.push(`  apps/${id}/LICENSE.md`.padEnd(46) + title);
  }

  console.log(rows.join('\n'));

  if (check) {
    if (stale.length) {
      console.error(`\n${stale.length} licence file(s) need regenerating. Run: pnpm gen:licenses`);
      process.exit(1);
    }
    console.log(`\nLicence check passed: all ${rows.length} generator apps carry a current LICENSE.md.`);
    return;
  }
  console.log(`\nWrote ${rows.length} licence files.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
