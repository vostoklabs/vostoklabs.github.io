// The tile library: Pattern Monster's 330 free tiles as patterns, each carrying its provenance.
// Loaded on demand — `import('@vostok/patterns/library')` — so an app that only wants the
// procedural patterns never pays for the data; `@vostok/patterns/library-index` is the small
// metadata file (names, tags, modes, ranges) a picker lists and filters without the geometry.
//
// Pattern Monster (https://pattern.monster, MIT, © 2020–2023 pattern.monster) — the tiles in
// data/pattern-monster.json are the free catalogue of its open-source repository
// (github.com/catchspider2002/svelte-svg-patterns), regenerated by
// scripts/fetch-pattern-monster.mjs. The licence text travels in
// data/pattern-monster.LICENSE.txt and goes into every bundle's THIRD-PARTY-NOTICES.
import { flattenPathData } from '../svgpath';
import type { PatternDef } from '../types';
import { svgTilePattern, type SvgTileSpec } from './svgtile';
import { inspireLook, surpriseValues, tileLayers, tileSvg, MONSTER_DARK, MONSTER_LIGHT, type MonsterTile, type MonsterTileMeta, type TileLook } from './tile-svg';
import { TILE_TUNING, isHiddenTile, type TileTuning } from './tuning';
import monster from '../../data/pattern-monster.json';

export const PATTERN_MONSTER_SOURCE = {
  name: 'Pattern Monster',
  licence: 'MIT',
  url: 'https://github.com/catchspider2002/svelte-svg-patterns',
} as const;

/** Every tile with its path data. */
export const LIBRARY_TILES: MonsterTile[] = (monster as unknown as { tiles: MonsterTile[] }).tiles;

/** The tiles the picker offers — every one but the hidden (`TILE_TUNING`). */
export const PICKER_TILES: MonsterTile[] = LIBRARY_TILES.filter((t) => !isHiddenTile(t.id));

/** The period in mm a tile reads at on a coaster: measured from its line density by the fetch
 *  script (`size`), else about 0.45 mm per tile unit, 8–40 mm. */
export const defaultSizeOf = (tile: MonsterTileMeta): number => tile.size ?? Math.round(Math.max(8, Math.min(40, tile.width * 0.45)) * 2) / 2;

export const tileById = (id: string): MonsterTile | undefined => LIBRARY_TILES.find((t) => t.id === id || `pm-${t.id}` === id);

export const PATTERN_MONSTER: PatternDef[] = LIBRARY_TILES.map((t) =>
  svgTilePattern(
    {
      id: `pm-${t.id}`,
      name: t.title,
      width: t.width,
      height: t.height,
      paths: t.paths,
      mode: t.mode,
      tags: ['pattern monster', ...t.tags],
      source: PATTERN_MONSTER_SOURCE,
      defaultSize: defaultSizeOf(t),
      maxSpacing: t.maxSpacing,
      maxStroke: t.maxStroke,
      ...(TILE_TUNING[t.id]?.thicken ? { thicken: TILE_TUNING[t.id]!.thicken } : {}),
    },
    flattenPathData,
  ),
);

export const LIBRARY: PatternDef[] = [...PATTERN_MONSTER];

export { svgTilePattern, tileSvg, tileLayers, inspireLook, surpriseValues, MONSTER_DARK, MONSTER_LIGHT, TILE_TUNING, isHiddenTile };
export type { SvgTileSpec, MonsterTile, MonsterTileMeta, TileLook, TileTuning };
