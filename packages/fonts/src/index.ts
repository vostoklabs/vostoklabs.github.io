/** The faces this build leaves out: an app whose package has a size limit drops a heavy face with
 *  `leaveOutFonts` (vite.js), which rewrites this line. Empty in every other build. */
const LEFT_OUT: readonly string[] = [];

/** Whether this build carries `fontId`'s file. A face left out is offered nowhere: not in a
 *  picker, not as a fallback. */
export const inThisBuild = (fontId: string): boolean => !LEFT_OUT.includes(fontId);

/** Every face of the library this build carries: the whole registry, unless faces were left out. */
export const FONTS: FontChoice[] = LEFT_OUT.length ? LIBRARY.filter((f) => inThisBuild(f.id)) : LIBRARY;

