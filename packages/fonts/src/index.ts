/** CSS font-family prefix for the @font-face rules in `@vostok/fonts/fonts.css`.
 *  Used for HTML previews only — the 3D geometry comes from opentype. */
export const FONT_FAMILY_PREFIX = 'VL-';

/** The CSS family name to preview `fontId` with. */
export const fontFamilyFor = (fontId: string): string => `${FONT_FAMILY_PREFIX}${fontId}`;


// Vite resolves this glob relative to THIS file, so it works from any app that
// consumes the package as source. `import: 'default'` yields URLs, not bytes —
// the fonts stay out of the JS bundle and are fetched only when used. Most faces are
// TrueType; a face shipped as its maker released it may be an OpenType/CFF `.otf`.
const fontUrls = (import.meta as any).glob(['./fonts/*.ttf', './fonts/*.otf'], {
  eager: true,
  import: 'default',
}) as Record<string, string>;

/** The face a picker draws `fontId`'s row in until its own file has loaded, for a face too heavy
 *  to fetch just to show a row (`FontChoice.preview`); undefined for every other face. */
const standInFor = (fontId: string): string | undefined => FONTS.find((f) => f.id === fontId)?.preview;

// In a build for the website every face comes from the site's one copy of it (site.ts); in any
// other build, from the app's own files.
const fontUrlById: Record<string, string> = Object.entries(fontUrls).reduce(
  (acc, [path, url]) => {
    acc[path.replace('./fonts/', '').replace(/\.(?:ttf|otf)$/, '')] = siteFontUrl(path, url);
    return acc;
  },
  {} as Record<string, string>,
);

/** Get the URL for a given font ID so the app can inject its own @font-face or use it directly. */
export const getFontUrl = (fontId: string): string | undefined => fontUrlById[fontId] ?? addedFontUrls.get(fontId);

/** Fonts imported by the user at runtime, parsed and held in memory. */
const customFonts = new Map<string, any>();

/** Parse a .ttf/.otf the user supplied. Kept here so apps never need to depend
 *  on opentype directly — the package owns the one copy. */
export function parseFont(buffer: ArrayBuffer): any {
  return opentype.parse(buffer);
}

/** Register a font the user imported from a .ttf/.otf, so `getFont` can find it. */
export function registerCustomFont(fontId: string, parsed: any): void {
  customFonts.set(fontId, parsed);
  fontCache.set(fontId, parsed);
}

async function loadFont(fontId: string): Promise<any> {
  const custom = customFonts.get(fontId);
  if (custom) return custom;
  const url = fontUrlById[fontId] ?? addedFontUrls.get(fontId);
  if (!url) {
    if (fontId.startsWith('custom-')) {
      throw new Error('Custom font is missing. Please import the .ttf/.otf file again.');
    }
    throw new Error(`Font url not resolved for ${fontId}`);
  }
  const r = await fetch(url);
  if (!r.ok) throw new Error(`Fetch failed for font ${fontId}`);
  const buffer = await r.arrayBuffer();
  if (standInFor(fontId)) declareFromFile(fontId, buffer);
  return opentype.parse(buffer);
}

/**
 * Declares a face with a stand-in to the page from the file `getFont` has just fetched for its
 * outlines, so nothing fetches it a second time. Such a face is in no stylesheet (`fonts.css`
 * leaves it out, `installFontFaces` skips it), so drawing its row never loads it: the row is
 * drawn in its stand-in until this runs, then in the face itself. No page, nothing to declare.
 */
function declareFromFile(fontId: string, buffer: ArrayBuffer): void {
  if (typeof FontFace === 'undefined' || typeof document === 'undefined') return;
  const face = new FontFace(fontFamilyFor(fontId), buffer.slice(0), { display: 'swap' });
  document.fonts.add(face);
  face.load().catch(() => document.fonts.delete(face));
}

/** Parsed opentype font for `fontId`, cached for the session. */
export async function getFont(fontId: string): Promise<any> {
  let f = fontCache.get(fontId);
  if (!f) {
    f = await loadFont(fontId);
    fontCache.set(fontId, f);
  }
  return f;
}

/** Loads and parses every face named, so `loadedFont` can hand each over without waiting. For
 *  code that has to draw synchronously: preload at start, then read. */
export async function preloadFonts(fontIds: readonly string[]): Promise<void> {
  await Promise.all(fontIds.map((id) => getFont(id)));
}

/** The parsed face for `fontId` when it has been loaded already this session (by `getFont`,
 *  `preloadFonts` or an import), else undefined. Never fetches. */
export const loadedFont = (fontId: string): any => fontCache.get(fontId);

/**
 * Declares each face to the document, from the same file `getFont` reads the outlines from, so
 * HTML can show text in it, and returns the function that takes them away again (for a host
 * that clears the page and mounts the app afresh: `document.fonts` outlives it). A face this
 * build has no file for is skipped.
 *
 * For an app that shows a few faces in the DOM without `@vostok/fonts/fonts.css`. That sheet
 * declares every face, and a build that inlines its assets then carries each twice, once for the
 * sheet and once for the outlines. A face added through the FontFace API is not a stylesheet, so
 * a host whose policy is `style-src 'self'` (which refuses an inline `<style>`) lets it through,
 * and it still loads lazily, the first time something is drawn in it.
 *
 * `weight` declares how heavy the faces are (`'700'` for Roboto Bold), so text set bold in that
 * family is drawn with the face as it is, not emboldened again by the browser. Left out, the
 * faces are declared without one, as before.
 *
 * A face with a stand-in (`FontChoice.preview`) is skipped too: declared here, the first row
 * drawn in it would fetch its whole file. It is declared once `getFont` has loaded it.
 */
export function installFontFaces(fontIds: readonly string[], opts: { display?: FontDisplay; weight?: string } = {}): () => void {
  const faces: FontFace[] = [];
  const descriptors: FontFaceDescriptors = { display: opts.display ?? 'block', ...(opts.weight ? { weight: opts.weight } : {}) };
  for (const id of fontIds) {
    const url = getFontUrl(id);
    if (!url || standInFor(id)) continue;
    const face = new FontFace(fontFamilyFor(id), `url("${url}")`, descriptors);
    document.fonts.add(face);
    faces.push(face);
  }
  return () => {
    for (const face of faces) document.fonts.delete(face);
  };
}

/** Fonts shown as instant cards; the rest live behind "Browse all fonts". */
export const curatedFonts = (): FontChoice[] => FONTS.filter((f) => f.curated);

/**
 * What a string needs from a font, so a face that would draw "?" or an empty box is flagged
 * before it does. One entry per kind of character the text holds, each a name a face lists in
 * `subsets` (`cyrillic`, `korean`, `kana`, `japanese`...), or two joined by `|` when either will
 * do: a Han character in both the Japanese and the Chinese set needs
 * `japanese|chinese-simplified`. `han` stands for a Han character past those common sets, which
 * a face must hold itself (`FontChoice.han`). `UNCOVERED` stands for a character no bundled face
 * has: a Hangul syllable past the common set, or Hangul typed as separate jamo. `latin-ext-b`
 * stands for a Latin Extended-B letter, which a face must hold itself (`FontChoice.latinExtB`).
 * Basic Latin, Latin-1 and punctuation need nothing.
 */
export function getRequiredSubsets(text: string): string[] {
  const needs = new Set<string>();
  for (const char of text) {
    const need = requirementOf(char.codePointAt(0)!);
    if (need) needs.add(need);
  }
  return Array.from(needs);
}

/** Every letter and digit of `text` is in this parsed font's cmap. */
function cmapCovers(parsed: any, text: string): boolean {
  const map: Record<number, number> | undefined = parsed?.tables?.cmap?.glyphIndexMap;
  if (!map) return true;
  for (const char of text) {
    if (/[\p{L}\p{N}]/u.test(char) && !map[char.codePointAt(0)!]) return false;
  }
  return true;
}

/** Whether `font` has every character in `text`. A bundled face answers from the coverage its
 *  file was measured to have; a font the user imported, from its own cmap, letter by letter. */
export function isFontSupported(font: FontChoice, text: string): boolean {
  const imported = customFonts.get(font.id);
  if (imported) return cmapCovers(imported, text);
  if (!font.subsets) return true;
  return getRequiredSubsets(text).every((need) =>
    need === LATIN_EXT_B ? holdsLatinExtB(font, text)
      : need === HAN ? holdsHan(font, text)
        : need.split('|').some((name) => font.subsets.includes(name)));
}

/** Every Han character of `text` past the common sets is one the face's file was measured to
 *  hold. A face without the measurement holds none of them: the cut CJK faces, and every face
 *  made somewhere other than the registry, as before there was one. */
function holdsHan(font: FontChoice, text: string): boolean {
  for (const char of text) {
    const cp = char.codePointAt(0)!;
    if (requirementOf(cp) === HAN && !(font.han !== undefined && runsHold(font.han, cp))) return false;
  }
  return true;
}

/** Every Latin Extended-B letter of `text` is one the face's file was measured to hold. A face
 *  without that measurement, made somewhere other than the registry, is not flagged for them. */
function holdsLatinExtB(font: FontChoice, text: string): boolean {
  if (font.latinExtB === undefined) return true;
  for (const char of text) {
    const cp = char.codePointAt(0)!;
    if (requirementOf(cp) === LATIN_EXT_B && !runsHold(font.latinExtB, cp)) return false;
  }
  return true;
}

/** The alphabets `font` writes, for a person to filter by: any of 'Latin', 'Cyrillic', 'Greek',
 *  'Korean', 'Japanese', 'Chinese', always in that order. A face with kana and no kanji counts
 *  as Japanese; a kanji typed in it is still flagged. */
export function fontScripts(font: FontChoice): string[] {
  return SCRIPTS.filter(([, names]) => names.some((name) => font.subsets?.includes(name))).map(([script]) => script);
}

/** The alphabets a face this package did not ship writes (a typeface an app parses itself), given
 *  a lookup into its characters: measured on the sets the registry's faces were measured on, and
 *  named as `fontScripts` names them, so a picker's Alphabet filter treats it like the rest. */
export function scriptsFromCmap(has: (codePoint: number) => boolean): string[] {
  return fontScripts({ subsets: coverageOf(has) } as FontChoice);
}

